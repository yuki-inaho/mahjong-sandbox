#!/usr/bin/env python3
"""Generate TypeScript from the Rust-exported, closed JSON Schema subset.

Unknown schema keywords or forms fail generation instead of degrading to `any`.
Run export-schema before this program; --check never rewrites either artifact.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ANNOTATIONS = {"$schema", "title", "description", "default", "definitions"}
SUPPORTED = ANNOTATIONS | {"$ref", "type", "enum", "oneOf", "anyOf", "allOf", "properties", "required", "additionalProperties", "items", "minItems", "maxItems", "minimum", "maximum", "pattern", "format", "minLength", "maxLength"}
FORMATS = {"uint8", "uint16", "uint32", "int8", "int16", "int32", "uint64-decimal", "int64-decimal"}


def literal(value: object) -> str:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))


def convert(schema: object, definitions: dict[str, object]) -> str:
    if not isinstance(schema, dict):
        raise ValueError("Boolean/non-object schemas are not supported")
    unknown = set(schema) - SUPPORTED
    if unknown:
        raise ValueError(f"Unsupported schema keywords: {sorted(unknown)}")
    if "format" in schema and schema["format"] not in FORMATS:
        raise ValueError(f"Unsupported format: {schema['format']}")
    if "$ref" in schema:
        name = str(schema["$ref"]).removeprefix("#/definitions/")
        if schema["$ref"] != f"#/definitions/{name}" or name not in definitions:
            raise ValueError(f"Unresolved schema reference: {schema['$ref']}")
        return name
    for key, operator in [("oneOf", " | "), ("anyOf", " | "), ("allOf", " & ")]:
        if key in schema:
            return "(" + operator.join(convert(child, definitions) for child in schema[key]) + ")"
    if "enum" in schema:
        if not schema["enum"]:
            raise ValueError("Empty enum")
        return " | ".join(literal(item) for item in schema["enum"])
    kind = schema.get("type")
    if isinstance(kind, list):
        return "(" + " | ".join(convert({**schema, "type": part}, definitions) for part in kind) + ")"
    if kind == "object":
        properties = schema.get("properties", {})
        required = set(schema.get("required", []))
        if required - set(properties):
            raise ValueError("Required property missing from properties")
        if schema.get("additionalProperties") is not False:
            raise ValueError("Every public object must reject unknown properties")
        fields = [f"readonly {literal(name)}{'' if name in required else '?'}: {convert(value, definitions)};" for name, value in properties.items()]
        return "{ " + " ".join(fields) + " }"
    if kind == "array":
        inner = convert(schema["items"], definitions)
        size = schema.get("minItems")
        if isinstance(size, int) and size == schema.get("maxItems") and size <= 4:
            return "readonly [" + ", ".join([inner] * size) + "]"
        return f"ReadonlyArray<{inner}>"
    if kind in {"integer", "number"}:
        if kind == "number":
            raise ValueError("Floating-point protocol fields need an explicit design decision")
        return "number"
    if kind in {"string", "boolean", "null"}:
        return kind
    raise ValueError(f"Undefined schema shape: {schema}")


def generate(schema: dict[str, object]) -> tuple[str, str]:
    definitions = schema["definitions"]
    lines = ["// Generated by scripts/generate_protocol_ts.py; edit the Rust wire types.", "// Numeric and text ranges are enforced by the runtime validator.", ""]
    for name, value in definitions.items():
        if re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*", name) is None:
            raise ValueError(f"Invalid TypeScript type name: {name}")
        lines.append(f"export type {name} = {convert(value, definitions)};")
    schema_source = "// Generated from bindings/protocol.schema.json. Do not edit.\nexport const protocolSchema: unknown = " + json.dumps(schema, ensure_ascii=False, indent=2) + ";\n"
    return "\n".join(lines) + "\n", schema_source


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    schema = json.loads((ROOT / "bindings/protocol.schema.json").read_text())
    types, runtime = generate(schema)
    for name, content in [("types.ts", types), ("schema.ts", runtime)]:
        path = ROOT / "packages/suzume/src/generated" / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Out-of-date generated file: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print("TypeScript protocol: checked" if args.check else "TypeScript protocol: generated")


if __name__ == "__main__":
    main()
